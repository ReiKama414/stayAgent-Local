const TABLE: Record<Lang, Record<string, Tpl>> = { en: EN, zh: ZH, ja: JA };

export function msg(lang: Lang) {
  const t = TABLE[lang] ?? EN;
  return (key: string, p: P = {}) => (t[key] ?? EN[key] ?? (() => key))(p);
}

