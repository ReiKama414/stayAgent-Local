export function translateStage(lang: Lang, s: string): string {
  if (lang === "en" || !s) return s;
  if (DICT[s]) return translate(lang, s);
  for (const [re, zh, ja] of STAGES) if (re.test(s)) return s.replace(re, lang === "zh" ? zh : ja);
  return s;
}
